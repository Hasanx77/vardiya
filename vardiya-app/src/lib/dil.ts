/** Çeviri. `{ad}` gibi yer tutucular `veri` ile doldurulur. */
export function t(
  dil: Dil,
  anahtar: SozlukAnahtari,
  veri?: Record<string, string | number>,
): string {
  const metin = SOZLUK[dil]?.[anahtar] ?? SOZLUK.tr[anahtar] ?? anahtar;
  if (!veri) return metin;
  return metin.replace(/\{(\w+)\}/g, (_, k: string) =>
    Object.prototype.hasOwnProperty.call(veri, k) ? String(veri[k]) : `{${k}}`,
  );
}
