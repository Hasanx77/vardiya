/**
 * Dil desteği (TR / EN) — tek sözlük.
 *
 * Tasarım:
 *   • Varsayılan **Türkçe**. Kullanıcı Ayarlar → Görünüm'den değiştirir.
 *   • Tercih iki yere yazılır: `Ayar` tablosu (cihazlar arası) + `vardiya-dil`
 *     çerezi (sunucu bileşenleri ilk boyamada doğru dili çizebilsin).
 *   • `t(dil, "anahtar", {n: 3})` → metin. Eksik anahtar Türkçeye düşer.
 *
 * Not: Yalnızca **arayüz** çevrilir; kullanıcı verisi (personel adı, vardiya
 * adı, duyuru) olduğu gibi gösterilir. Tarih/saat biçimi `Intl` ile dile uyar.
 */

export type Dil = "tr" | "en";

export const DIL_COOKIE = "vardiya-dil";
export const VARSAYILAN_DIL: Dil = "tr";

export const DILLER: { id: Dil; ad: string; kisa: string }[] = [
  { id: "tr", ad: "Türkçe", kisa: "TR" },
  { id: "en", ad: "English", kisa: "EN" },
];

export function dilGecerliMi(deger: string): deger is Dil {
  return deger === "tr" || deger === "en";
}

export function dilOku(cerez: string | undefined | null): Dil {
  const d = String(cerez ?? "").trim().toLowerCase();
  return dilGecerliMi(d) ? d : VARSAYILAN_DIL;
}

/** Yerel ayar kodu: Intl için. */
export function yerel(dil: Dil): string {
  return dil === "en" ? "en-GB" : "tr-TR";
}

